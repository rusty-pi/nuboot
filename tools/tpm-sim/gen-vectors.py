#!/usr/bin/env python3
"""Reference vectors for tests/primitives.rs: P-256, AES-CFB, KDFa and KDFe,
computed with Python's `cryptography` and plain integer arithmetic, so the
firmware's implementations are checked against something that is not them.

    gen-vectors.py > tests/vectors.rs
"""

import hashlib
import hmac
import os
import random
import struct

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature, Prehashed
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
rng = random.Random(7)


def be(x, n=32):
    return x.to_bytes(n, "big")


def arr(b):
    return "[" + ", ".join(f"0x{x:02x}" for x in b) + "]"


def pub(d):
    k = ec.derive_private_key(d, ec.SECP256R1())
    n = k.public_key().public_numbers()
    return k, n.x, n.y


def kdfa(key, label, u, v, bits):
    out = b""
    i = 1
    while len(out) * 8 < bits:
        out += hmac.new(key, struct.pack(">I", i) + label + b"\0" + u + v + struct.pack(">I", bits), hashlib.sha256).digest()
        i += 1
    out = out[: (bits + 7) // 8]
    if bits % 8:
        out = bytes([out[0] & (0xFF >> (8 - bits % 8))]) + out[1:]
    return out


def kdfe(z, label, u, v, bits):
    out = b""
    i = 1
    while len(out) * 8 < bits:
        out += hashlib.sha256(struct.pack(">I", i) + z + label + b"\0" + u + v).digest()
        i += 1
    return out[: (bits + 7) // 8]


def inv(a, m):
    return pow(a, -1, m)


print("// Generated by gen-vectors.py; do not edit.")
print()
print("pub struct Keypair { pub d: [u8; 32], pub x: [u8; 32], pub y: [u8; 32] }")
print("pub const KEYS: &[Keypair] = &[")
keys = []
for _ in range(4):
    d = rng.randrange(1, N)
    k, x, y = pub(d)
    keys.append((d, k, x, y))
    print(f"    Keypair {{ d: {arr(be(d))}, x: {arr(be(x))}, y: {arr(be(y))} }},")
print("];")
print()
print("/// `(d of one, public key of another, x of the shared point)`")
print("pub const ECDH: &[([u8; 32], [u8; 32], [u8; 32], [u8; 32])] = &[")
for i in range(4):
    j = (i + 1) % 4
    shared = keys[i][1].exchange(ec.ECDH(), keys[j][1].public_key())
    print(f"    ({arr(be(keys[i][0]))}, {arr(be(keys[j][2]))}, {arr(be(keys[j][3]))}, {arr(shared)}),")
print("];")
print()
print("/// `(d, k, digest, r, s)`: the ECDSA signature with that nonce, by arithmetic.")
print("pub const SIGNATURES: &[([u8; 32], [u8; 32], [u8; 32], [u8; 32], [u8; 32])] = &[")
sigs = []
for i in range(4):
    d = keys[i][0]
    kk = rng.randrange(1, N)
    digest = hashlib.sha256(os.urandom(8)).digest()
    # R = k*G, via the library: a throwaway key with that scalar.
    _, rx, _ = pub(kk)
    r = rx % N
    s = inv(kk, N) * (int.from_bytes(digest, "big") % N + r * d) % N
    sigs.append((d, kk, digest, r, s))
    print(f"    ({arr(be(d))}, {arr(be(kk))}, {arr(digest)}, {arr(be(r))}, {arr(be(s))}),")
print("];")
print()
print("/// `(public x, y, digest, r, s)` signed by the library with its own nonce.")
print("pub const LIBRARY_SIGNATURES: &[([u8; 32], [u8; 32], [u8; 32], [u8; 32], [u8; 32])] = &[")
for i in range(3):
    d, k, x, y = keys[i]
    digest = hashlib.sha256(os.urandom(8)).digest()
    der = k.sign(digest, ec.ECDSA(Prehashed(hashes.SHA256())))
    r, s = decode_dss_signature(der)
    print(f"    ({arr(be(x))}, {arr(be(y))}, {arr(digest)}, {arr(be(r))}, {arr(be(s))}),")
print("];")
print()
print("/// `(key, iv, plaintext, ciphertext)`, AES-128-CFB.")
print("pub const CFB: &[([u8; 16], [u8; 16], &[u8], &[u8])] = &[")
for n in (0, 5, 16, 37, 64):
    key, iv, pt = os.urandom(16), os.urandom(16), os.urandom(n)
    enc = Cipher(algorithms.AES(key), modes.CFB(iv)).encryptor()
    ct = enc.update(pt) + enc.finalize()
    print(f"    ({arr(key)}, {arr(iv)}, &{arr(pt)}, &{arr(ct)}),")
print("];")
print()
print("/// `(key, label, u, v, bits, output)`.")
print("pub const KDFA: &[(&[u8], &[u8], &[u8], &[u8], u32, &[u8])] = &[")
for bits in (128, 256, 384, 320, 100):
    key, u, v = os.urandom(32), os.urandom(8), os.urandom(5)
    print(f"    (&{arr(key)}, b\"STORAGE\", &{arr(u)}, &{arr(v)}, {bits}, &{arr(kdfa(key, b'STORAGE', u, v, bits))}),")
print("];")
print()
print("/// `(z, label, u, v, bits, output)`.")
print("pub const KDFE: &[(&[u8], &[u8], &[u8], &[u8], u32, &[u8])] = &[")
for bits in (256, 384):
    z, u, v = os.urandom(32), os.urandom(32), os.urandom(32)
    print(f"    (&{arr(z)}, b\"SECRET\", &{arr(u)}, &{arr(v)}, {bits}, &{arr(kdfe(z, b'SECRET', u, v, bits))}),")
print("];")
print()
print("/// `(modulus, exponent, digest, signature, valid)`: RSA-2048, -3072 and -4096 PKCS#1 v1.5 with SHA-256.")
print("pub const RSA: &[(&[u8], u32, [u8; 32], &[u8], bool)] = &[")
from cryptography.hazmat.primitives.asymmetric import padding, rsa

for exponent, bits in ((65537, 2048), (65537, 2048), (3, 2048), (65537, 3072), (65537, 4096), (3, 3072)):
    key = rsa.generate_private_key(public_exponent=exponent, key_size=bits)
    modulus = be(key.public_key().public_numbers().n, bits // 8)
    digest = hashlib.sha256(os.urandom(8)).digest()
    signature = key.sign(digest, padding.PKCS1v15(), Prehashed(hashes.SHA256()))
    print(f"    (&{arr(modulus)}, {exponent}, {arr(digest)}, &{arr(signature)}, true),")
    other = bytes([digest[0] ^ 1]) + digest[1:]
    print(f"    (&{arr(modulus)}, {exponent}, {arr(other)}, &{arr(signature)}, false),")
print("];")
print()
print("/// `(d, x of d * G)` for scalars at the edges of the generator tables' windows and halves.")
print("pub const EDGE_KEYS: &[([u8; 32], [u8; 32])] = &[")
for d in (1, 2, 15, 16, 255, 1 << 127, 1 << 128, (1 << 128) + 1, (0xF << 128) | 0xF, (1 << 252) | 1, N - 1, N - 2):
    k, x, y = pub(d)
    print(f"    ({arr(be(d))}, {arr(be(x))}),")
print("];")
