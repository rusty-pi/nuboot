//! The log as text on the HDMI framebuffer ([`crate::hdmi`]): the console's
//! lines, in an 8x8 font drawn twice as tall, white on black. When the text
//! reaches the bottom the screen is cleared and the next line starts at the top.

use core::fmt::{self, Write};
use core::sync::atomic::{AtomicU32, Ordering};

use crate::hdmi::{BASE, HEIGHT, WIDTH};
use crate::log::{self, Record, Sink};

const CELL_W: u32 = 8;
const CELL_H: u32 = 16;
const COLUMNS: u32 = WIDTH / CELL_W;
const ROWS: u32 = HEIGHT / CELL_H;
const FOREGROUND: u32 = 0x00ff_ffff;
const BACKGROUND: u32 = 0;

/// The framebuffer through the uncached alias of the ARM's memory, so what
/// is drawn is what the scan-out reads.
const UNCACHED: u32 = 0xc000_0000;

fn pixels() -> *mut u32 {
    (UNCACHED | BASE) as usize as *mut u32
}

/// Set the framebuffer to the background colour.
pub fn clear() {
    for i in 0..(WIDTH * HEIGHT) as usize {
        unsafe { pixels().add(i).write_volatile(BACKGROUND) };
    }
}

fn draw(column: u32, row: u32, c: u8) {
    let glyph = &FONT[(if (0x20..0x7f).contains(&c) { c } else { b'?' } - 0x20) as usize];
    for (y, bits) in glyph.iter().enumerate() {
        for dy in 0..2 {
            let line = (row * CELL_H + y as u32 * 2 + dy) * WIDTH + column * CELL_W;
            for x in 0..CELL_W {
                let on = bits >> x & 1 != 0;
                unsafe { pixels().add((line + x) as usize).write_volatile(if on { FOREGROUND } else { BACKGROUND }) };
            }
        }
    }
}

/// Where the next character goes, and how far into an escape sequence the
/// text is: the colour codes of the `color` feature are skipped.
static COLUMN: AtomicU32 = AtomicU32::new(0);
static ROW: AtomicU32 = AtomicU32::new(0);
static ESCAPE: AtomicU32 = AtomicU32::new(0);

struct Screen;

impl Screen {
    fn newline(&mut self) {
        COLUMN.store(0, Ordering::Relaxed);
        let row = ROW.load(Ordering::Relaxed) + 1;
        if row == ROWS {
            clear();
            ROW.store(0, Ordering::Relaxed);
        } else {
            ROW.store(row, Ordering::Relaxed);
        }
    }

    fn put(&mut self, c: u8) {
        if ESCAPE.load(Ordering::Relaxed) != 0 {
            if c.is_ascii_alphabetic() {
                ESCAPE.store(0, Ordering::Relaxed);
            }
            return;
        }
        match c {
            0x1b => ESCAPE.store(1, Ordering::Relaxed),
            b'\n' => self.newline(),
            b'\r' => COLUMN.store(0, Ordering::Relaxed),
            _ => {
                if COLUMN.load(Ordering::Relaxed) == COLUMNS {
                    self.newline();
                }
                let column = COLUMN.load(Ordering::Relaxed);
                draw(column, ROW.load(Ordering::Relaxed), c);
                COLUMN.store(column + 1, Ordering::Relaxed);
            }
        }
    }
}

impl Write for Screen {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        s.bytes().for_each(|c| self.put(c));
        Ok(())
    }
}

pub struct ScreenSink;

static SINK: ScreenSink = ScreenSink;

impl Sink for ScreenSink {
    fn record(&self, record: &Record) {
        let _ = log::render(&mut Screen, record);
    }
}

/// Clear the screen and send every record from here on to it too.
pub fn attach() -> bool {
    clear();
    log::attach(&SINK)
}

