#!/usr/bin/env python3
"""The tables `src/p256.rs` multiplies the generator with: j*G and j*2^128*G
for j from 1 to 15, affine, in Montgomery form modulo the field prime, as
little-endian 32-bit limbs.

    gen-p256-tables.py > src/p256_tables.rs
"""

P = 0xFFFFFFFF00000001000000000000000000000000FFFFFFFFFFFFFFFFFFFFFFFF
GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
GY = 0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5


def add(p, q):
    if p is None:
        return q
    if q is None:
        return p
    if p[0] == q[0]:
        if (p[1] + q[1]) % P == 0:
            return None
        m = (3 * p[0] * p[0] - 3) * pow(2 * p[1], -1, P) % P
    else:
        m = (q[1] - p[1]) * pow(q[0] - p[0], -1, P) % P
    x = (m * m - p[0] - q[0]) % P
    return x, (m * (p[0] - x) - p[1]) % P


def limbs(x):
    mont = x * (1 << 256) % P
    return "[" + ", ".join(f"0x{(mont >> (32 * i)) & 0xFFFFFFFF:08x}" for i in range(8)) + "]"


def table(base):
    entries, point = [], None
    for _ in range(15):
        point = add(point, base)
        entries.append(point)
    return entries


high = (GX, GY)
for _ in range(128):
    high = add(high, high)

print("// Generated by scripts/gen-p256-tables.py; do not edit.")
for name, base in (("LOW", (GX, GY)), ("HIGH", high)):
    print(f"\n/// `j * {'G' if name == 'LOW' else '2^128 * G'}` for `j` from 1 to 15: x and y in Montgomery form.")
    print(f"const {name}: [[Limbs; 2]; 15] = [")
    for x, y in table(base):
        print(f"    [{limbs(x)}, {limbs(y)}],")
    print("];")
